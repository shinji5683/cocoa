        // 1. 漢字辞書に一致
        kanjiMap[ch]?.let { return it }

        // 2. ひらがな・カタカナ・英数字・記号
        return when (ch) {
            in 'a'..'z' -> "小文字のアルファベット「$ch」"
            in 'A'..'Z' -> "大文字のアルファベット「$ch」"
            in '0'..'9' -> "数字の「$ch」"
            ' ' -> "スペース（空白）"
            '　' -> "全角スペース"
            '、' -> "読点（とうてん、てん）"
            '。' -> "句点（くてん、まる）"
            '！', '!' -> "感嘆符（びっくりマーク）"
            '？', '?' -> "疑問符（はてなマーク）"
            '・' -> "中黒（なかぐろ、なかてん）"
            'ー', '―' -> "長音記号（のばしぼう）"
            '「', '『' -> "カギ括弧の開き"
            '」', '』' -> "カギ括弧の閉じ"
            '（', '(' -> "丸括弧の開き"
            '）', ')' -> "丸括弧の閉じ"
            '@', '＠' -> "アットマーク"
            '#', '＃' -> "シャープ（ハッシュタグ）"
            '&', '＆' -> "アンド（アンパサンド）"
            '/', '／' -> "スラッシュ"
            ':', '：' -> "コロン"
            ';', '；' -> "セミコロン"
            '+', '＋' -> "プラス記号"
            '-', '−' -> "マイナス記号（ハイフン）"
            '=' -> "イコール（等号）"
            '%' -> "パーセント"
            '¥', '￥' -> "円記号（円マーク）"
            '$', '＄' -> "ドル記号"
            '~', '〜' -> "波ダッシュ（から）"
            else -> {
                if (ch.isWhitespace()) "空白文字"
                else "文字「$ch」"
            }
        }
    }

    /**
     * 文字列全体（例: 「Shinji」「東京」「賞味期限」）を1文字ずつ漢字詳細解説して連結した音声ガイドを生成
     */
    fun explainWord(text: String): String {
        if (text.isBlank()) return ""
        val sb = StringBuilder()
        for (i in text.indices) {
            val c = text[i]
            val explanation = explainChar(c)
            sb.append(c).append("、").append(explanation)
            if (i < text.length - 1) {
                sb.append("。次に、")
            }
        }
        return sb.toString()
    }

    /**
     * 音声入力やIME入力された文章の句読点抜け・誤変換を完全ローカルで自然に補正
     */
    fun smartFormatVoiceText(rawText: String): String {
        var text = rawText.trim()
        if (text.isEmpty()) return ""

        // 頻出音声認識の口語補正
        text = text.replace("しょうみきげん", "賞味期限")
            .replace("しょうひきげん", "消費期限")
            .replace("てんじぶろっく", "点字ブロック")
            .replace("しんごうき", "信号機")
            .replace("あおしんごう", "青信号")
            .replace("あかしんごう", "赤信号")
            .replace("せれな", "セレナ")
            .replace("ここあ", "ココア")

        // 文末の自動句点（すでに句読点や感嘆符がない場合に追加）
        if (!text.endsWith("。") && !text.endsWith("！") && !text.endsWith("？") && !text.endsWith("!") && !text.endsWith("?")) {
            text += "。"
        }
        return text
    }
